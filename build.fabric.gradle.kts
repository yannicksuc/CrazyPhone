plugins {
    `java-library`
    `maven-publish`
    idea
    `jvm-test-suite`
    id("fabric-loom") version "1.10-SNAPSHOT"
}

version = property("mod_version") as String
group = property("mod_group_id") as String

// Same charset fix as the NeoForge template (build.gradle.kts) - see that file for the full explanation.
tasks.withType<JavaCompile>().configureEach {
    options.encoding = "UTF-8"
    options.compilerArgs.add("-Xmaxerrs")
    options.compilerArgs.add("10000")
}

repositories {
    mavenLocal()
    // Modrinth's Maven - lets Camerapture be declared as a normal Gradle dependency instead of a
    // hand-copied jar in libs/ (unlike the NeoForge side's Camera mod dependency, which has no such
    // repository available and must be dropped into libs/ manually - see build.gradle.kts).
    exclusiveContent {
        forRepository { maven("https://api.modrinth.com/maven") { name = "Modrinth" } }
        filter { includeGroup("maven.modrinth") }
    }
}

base {
    archivesName = property("mod_id") as String
}

tasks.withType<AbstractArchiveTask>().configureEach {
    isPreserveFileTimestamps = true
    isReproducibleFileOrder = false
}

// Same Java-version boundary as the NeoForge side: 1.20.1 runs on Java 17, everything from 1.20.5 (and
// thus every later Fabric node we add) needs Java 21.
val minecraftVersionForToolchain = property("minecraft_version") as String
java.toolchain.languageVersion = JavaLanguageVersion.of(if (minecraftVersionForToolchain.startsWith("1.20")) 17 else 21)

val minecraftVersion = property("minecraft_version") as String
val fabricLoaderVersion = property("fabric_loader_version") as String
val fabricApiVersion = property("fabric_api_version") as String
val camerapturePinnedVersion = property("camerapture_version") as String

dependencies {
    minecraft("com.mojang:minecraft:$minecraftVersion")
    // Official Mojang mappings (not Yarn's obfuscated-then-remapped names) - this is what keeps the
    // shared src/main/java tree source-compatible between the NeoForge and Fabric nodes: NeoForge only
    // ever uses Mojmap, so matching it here means class/method/field names line up identically on both
    // loaders and the vast majority of loader-agnostic code needs zero renaming to compile under Loom.
    mappings(loom.officialMojangMappings())

    modImplementation("net.fabricmc:fabric-loader:$fabricLoaderVersion")
    modImplementation("net.fabricmc.fabric-api:fabric-api:$fabricApiVersion")

    // maven.modrinth:<slug>:<version> - see the Modrinth exclusiveContent repository above.
    modImplementation("maven.modrinth:camerapture:$camerapturePinnedVersion")
}

loom {
    runs {
        named("client") {
            client()
            programArgs("--username", "LordFinn")
            runDir = "run-$minecraftVersion-fabric"
        }
        named("server") {
            server()
            runDir = "run-$minecraftVersion-fabric-server"
        }
    }
}

testing {
    suites {
        named<JvmTestSuite>("test") {
            useJUnitJupiter("5.10.2")
            dependencies {
                implementation("org.mockito:mockito-core:5.11.0")
            }
        }
    }
}

// Include resources generated by data generators, same as the NeoForge side.
sourceSets.main {
    resources.srcDir(rootProject.file("src/generated/resources"))
}

// WALKING-SKELETON STAGE: the shared src/main/java tree is still 100% NeoForge-only code (DeferredRegister,
// IEventBus, @Mod, PayloadRegistrar, ...), none of which compiles against Fabric Loader APIs. Rather than
// //? if fabric/neoforge-gate every one of those ~150 files in one pass, this walking skeleton excludes the
// whole tree except a new fr.lordfinn.crazyphone.fabric package (the Fabric entrypoint/registration glue,
// parallel to Crazyphone.java/ModItems.java/etc.) so the Loom+Stonecutter wiring itself can be verified
// end-to-end (compiles, mod loads, boots) before real features get ported back in one at a time. Follow-up
// milestones progressively narrow this exclude as each area (items, data, network, screens, mixins) gets
// its Fabric implementation written.
sourceSets.main {
    java.setIncludes(listOf("fr/lordfinn/crazyphone/fabric/**"))
}

// fabric.mod.json is expanded from a template the same way neoforge.mods.toml is - see
// src/main/templates/fabric.mod.json and generateModMetadata below.
val modMetadataProperties = mapOf(
    "minecraft_version" to property("minecraft_version"),
    "mod_id" to property("mod_id"),
    "mod_name" to property("mod_name"),
    "mod_license" to property("mod_license"),
    "mod_version" to property("mod_version"),
    "mod_authors" to property("mod_authors"),
    "mod_description" to property("mod_description"),
    "fabric_loader_version_range" to property("fabric_loader_version_range")
)
val generateModMetadata = tasks.register<ProcessResources>("generateModMetadata") {
    inputs.properties(modMetadataProperties)
    expand(modMetadataProperties)
    from(rootProject.file("src/main/templates/fabric"))
    into("build/generated/sources/modMetadata")
}
sourceSets.main {
    resources.srcDir(generateModMetadata)
}

